import '../../../models/import_requirement_model.dart';

class HsSyncHelper {
  const HsSyncHelper._();

  static ImportRequirementHSCodeItemModel syncCurrentItem({
    required ImportRequirementHSCodeItemModel current,
    required String hsCode,
    required String commodityDescription,
    required String countryOfOrigin,
    required String currency,
    required String itemValueStr,
    required bool decree43Applicable,
    required bool whiteListRequired,
    required bool whiteListVerified,
    required String? decree43Action,
    required String? decree43Justification,
    required String factoryRegistrationNo,
    required bool cooRequired,
    required String? cooType,
    required String cooStatus,
    required String cooNotes,
    required bool inspectionRequired,
    required String? inspectionBody,
    required String inspectionStatus,
    required String inspectionReportNo,
    required String inspectionNotes,
    required bool permitRequired,
    required String? regulatoryAuthority,
    required String permitNumber,
    required String permitStatus,
    required String permitNotes,
    required bool msdsRequired,
    required String msdsStatus,
    required String msdsNotes,
    required bool halalCertRequired,
    required String halalCertStatus,
    required String halalCertNotes,
    required bool coaRequired,
    required String coaStatus,
    required String coaNotes,
    required String specialNotes,
  }) {
    return current.copyWith(
      hsCode: hsCode,
      commodityDescription: commodityDescription,
      countryOfOrigin: countryOfOrigin,
      currency: currency,
      itemValue: double.tryParse(itemValueStr) ?? current.itemValue,
      decree43Applicable: decree43Applicable,
      whiteListRequired: whiteListRequired,
      whiteListVerified: whiteListVerified,
      decree43Action: decree43Action,
      decree43Justification: decree43Justification,
      factoryRegistrationNo: factoryRegistrationNo,
      cooRequired: cooRequired,
      cooType: cooType,
      cooStatus: cooStatus,
      cooNotes: cooNotes,
      inspectionRequired: inspectionRequired,
      inspectionBody: inspectionBody,
      inspectionStatus: inspectionStatus,
      inspectionReportNo: inspectionReportNo,
      inspectionNotes: inspectionNotes,
      permitRequired: permitRequired,
      regulatoryAuthority: regulatoryAuthority,
      permitNumber: permitNumber,
      permitStatus: permitStatus,
      permitNotes: permitNotes,
      msdsRequired: msdsRequired,
      msdsStatus: msdsStatus,
      msdsNotes: msdsNotes,
      halalCertRequired: halalCertRequired,
      halalCertStatus: halalCertStatus,
      halalCertNotes: halalCertNotes,
      coaRequired: coaRequired,
      coaStatus: coaStatus,
      coaNotes: coaNotes,
      specialNotes: specialNotes,
    );
  }

  static Map<String, dynamic> buildPayload({
    required int? selectedImportFileId,
    required String? selectedImportFileCode,
    required String hsCode,
    required String commodityDescription,
    required String countryOfOrigin,
    required String currency,
    required String itemValueStr,
    required List<ImportRequirementHSCodeItemModel> hsCodeItems,
    required int? selectedSupplierId,
    required String? selectedSupplierName,
    required bool decree43Applicable,
    required bool whiteListRequired,
    required bool whiteListVerified,
    required String? decree43Action,
    required String? decree43Justification,
    required String factoryRegistrationNo,
    required bool cooRequired,
    required String? cooType,
    required String cooStatus,
    required String cooNotes,
    required bool inspectionRequired,
    required String? inspectionBody,
    required String inspectionStatus,
    required String inspectionReportNo,
    required String inspectionNotes,
    required bool importPermitRequired,
    required String? permitIssuingAuthority,
    required String permitNumber,
    required String permitStatus,
    required String permitNotes,
    required bool msdsRequired,
    required String msdsStatus,
    required String msdsNotes,
    required bool halalCertRequired,
    required String halalCertStatus,
    required String halalCertNotes,
    required bool coaRequired,
    required String coaStatus,
    required String coaNotes,
    required bool cargoxVerified,
    required String cargoxStatus,
    required bool isShelflifeApplicable,
    required bool samplingRequired,
    required String? labType,
    required bool isHazmat,
    required String? imoClass,
    required String acidNumber,
    required int? consultationId,
    required String? consultationCode,
    required String confirmationStatus,
    required bool isPostAcidConfirmed,
    required String sailingStatus,
    required String sailingDate,
    required String overallStatus,
    required String riskLevel,
    required String assessedBy,
    required String assessmentNotes,
  }) {
    final parsedVal = double.tryParse(itemValueStr) ?? 0.0;
    return {
      'import_file_id': selectedImportFileId,
      'import_file_code': selectedImportFileCode,
      'hs_code': hsCode,
      'commodity_description': commodityDescription,
      'country_of_origin': countryOfOrigin,
      'currency': currency,
      'shipment_value': parsedVal,
      'shipment_value_usd': parsedVal,
      'hs_code_items': hsCodeItems.map((e) => e.toJson()).toList(),
      'supplier_id': selectedSupplierId,
      'supplier_name': selectedSupplierName,
      'decree_43_applicable': decree43Applicable,
      'white_list_required': whiteListRequired,
      'white_list_verified': whiteListVerified,
      'decree_43_action': decree43Action,
      'decree_43_justification': decree43Justification,
      'factory_registration_no': factoryRegistrationNo,
      'coo_required': cooRequired,
      'coo_type': cooType,
      'coo_status': cooStatus,
      'coo_notes': cooNotes,
      'inspection_required': inspectionRequired,
      'inspection_body': inspectionBody,
      'inspection_status': inspectionStatus,
      'inspection_report_no': inspectionReportNo,
      'inspection_notes': inspectionNotes,
      'import_permit_required': importPermitRequired,
      'permit_issuing_authority': permitIssuingAuthority,
      'permit_number': permitNumber,
      'permit_status': permitStatus,
      'permit_notes': permitNotes,
      'msds_required': msdsRequired,
      'msds_status': msdsStatus,
      'msds_notes': msdsNotes,
      'halal_cert_required': halalCertRequired,
      'halal_cert_status': halalCertStatus,
      'halal_cert_notes': halalCertNotes,
      'coa_required': coaRequired,
      'coa_status': coaStatus,
      'coa_notes': coaNotes,
      'cargox_verified': cargoxVerified,
      'cargox_status': cargoxStatus,
      'is_shelflife_applicable': isShelflifeApplicable,
      'sampling_required': samplingRequired,
      'lab_type': labType,
      'is_hazmat': isHazmat,
      'imo_class': imoClass,
      'acid_number': acidNumber,
      'consultation_id': consultationId,
      'consultation_code': consultationCode,
      'confirmation_status': confirmationStatus,
      'is_post_acid_confirmed': isPostAcidConfirmed,
      'confirmed_at': isPostAcidConfirmed ? DateTime.now().toIso8601String() : null,
      'confirmed_by': assessedBy,
      'sailing_status': sailingStatus,
      'sailing_date': sailingDate,
      'overall_status': overallStatus,
      'risk_level': riskLevel,
      'assessed_by': assessedBy,
      'assessment_notes': assessmentNotes,
    };
  }
}
