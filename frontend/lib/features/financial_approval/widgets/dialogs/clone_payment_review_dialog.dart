import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';

import '../../../../core/localization/app_localizations.dart';
import '../../../../core/network/api_error.dart';
import '../../../../core/theme/app_theme.dart';
import 'package:frontend/core/widgets/widgets.dart';
import '../../models/financial_approval_model.dart';
import '../../providers/financial_approval_provider.dart';

class ClonePaymentReviewDialog {
  static Future<void> show({
    required BuildContext context,
    required WidgetRef ref,
    required PaymentRequestModel payment,
    required void Function(PaymentRequestModel cloned) onCloned,
  }) async {
    final l = context.l10n;

    return showDialog(
      context: context,
      builder: (ctx) => AppLocalizationsProvider(
        locale: Localizations.localeOf(context),
        child: Directionality(
          textDirection: Directionality.of(context),
          child: CloneEntityReviewDialog(
            entityType: l.clonePaymentRequestDialogTitle,
            sourceCode: payment.paymentCode,
            sourceTitle: payment.title,
            suggestedNewCode: l.autoGeneratedCode,
            copiedFieldsSummary: {
              l.beneficiarySupplierLabel:
                  payment.beneficiaryName ?? payment.supplierName,
              l.requestedAmountLabel:
                  '${payment.requestedAmount.toStringAsFixed(2)} ${payment.currencyCode}',
              l.paymentTypeLabel: payment.paymentType,
              if (payment.bankName != null && payment.bankName!.isNotEmpty)
                l.bankNameLabel: payment.bankName!,
            },
            mandatorilyResetFields: [
              l.cloneFieldPaymentStatusReset,
              l.cloneFieldSwiftReceiptReset,
              l.cloneFieldBankingDetailsCopied,
              l.cloneFieldPaymentCodeGenerated,
            ],
            allowCopyLineItems: true,
            onConfirm: ({
              required String newCode,
              required String newTitle,
              required bool copyLineItems,
              required bool copyAttachments,
              String? notes,
            }) async {
              try {
                final payload = <String, dynamic>{
                  'new_title': newTitle,
                  'unlink_import_file': !copyLineItems,
                  if (notes != null && notes.trim().isNotEmpty)
                    'remarks': notes.trim(),
                };
                final cloned = await ref
                    .read(paymentRequestsProvider.notifier)
                    .clonePaymentRequest(payment.paymentId, payload);

                if (cloned != null && context.mounted) {
                  onCloned(cloned);

                  ScaffoldMessenger.of(context).showSnackBar(
                    AppTheme.snackBar(
                      context,
                      l.clonePaymentRequestSuccess(cloned.paymentCode),
                      severity: AppSeverity.success,
                    ),
                  );
                }
              } catch (e) {
                if (context.mounted) {
                  ScaffoldMessenger.of(context).showSnackBar(
                    AppTheme.snackBar(
                      context,
                      l.clonePaymentRequestError(ApiError.message(e)),
                      severity: AppSeverity.danger,
                    ),
                  );
                }
              }
            },
          ),
        ),
      ),
    );
  }
}
