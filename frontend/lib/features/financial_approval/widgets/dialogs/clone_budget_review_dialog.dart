import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';

import '../../../../core/localization/app_localizations.dart';
import '../../../../core/network/api_error.dart';
import '../../../../core/theme/app_theme.dart';
import 'package:frontend/core/widgets/widgets.dart';
import '../../models/financial_approval_model.dart';
import '../../providers/financial_approval_provider.dart';

class CloneBudgetReviewDialog {
  static Future<void> show({
    required BuildContext context,
    required WidgetRef ref,
    required ImportBudgetModel budget,
    required void Function(ImportBudgetModel cloned) onCloned,
  }) async {
    final l = context.l10n;

    return showDialog(
      context: context,
      builder: (ctx) => AppLocalizationsProvider(
        locale: Localizations.localeOf(context),
        child: Directionality(
          textDirection: Directionality.of(context),
          child: CloneEntityReviewDialog(
            entityType: l.cloneBudgetDialogTitle,
            sourceCode: budget.budgetCode,
            sourceTitle: budget.title,
            suggestedNewCode: l.autoGeneratedCode,
            copiedFieldsSummary: {
              l.estimatedInvoiceValue:
                  '${budget.invoiceAmountForeign.toStringAsFixed(2)} ${budget.invoiceCurrency}',
              l.estimatedFreightCost:
                  '${budget.freightCostForeign.toStringAsFixed(2)} ${budget.freightCurrency}',
              l.customsAndVatEstimate:
                  '${budget.customsDutiesEgp.toStringAsFixed(2)} EGP',
              l.clearanceAndTransportEstimate:
                  '${budget.clearanceInlandEgp.toStringAsFixed(2)} EGP',
              l.exchangeRateLabel: budget.exchangeRate.toStringAsFixed(2),
              l.totalBudgetEgp: '${budget.totalBudgetEgp.toStringAsFixed(2)} EGP',
            },
            mandatorilyResetFields: [
              l.cloneFieldBudgetStatusReset,
              l.cloneFieldCertificationsReset,
              l.cloneFieldExchangeRatesCopied,
              l.cloneFieldBudgetCodeGenerated,
            ],
            allowCopyLineItems: true,
            onConfirm: ({
              required String newCode,
              required String newTitle,
              required bool copyLineItems,
              required bool copyAttachments,
              String? notes,
            }) async {
              try {
                final payload = <String, dynamic>{
                  'new_title': newTitle,
                  'unlink_import_file': !copyLineItems,
                  if (notes != null && notes.trim().isNotEmpty)
                    'remarks': notes.trim(),
                };
                final cloned = await ref
                    .read(importBudgetsProvider.notifier)
                    .cloneImportBudget(budget.budgetId, payload);

                if (cloned != null && context.mounted) {
                  onCloned(cloned);

                  ScaffoldMessenger.of(context).showSnackBar(
                    AppTheme.snackBar(
                      context,
                      l.cloneBudgetSuccess(cloned.budgetCode),
                      severity: AppSeverity.success,
                    ),
                  );
                }
              } catch (e) {
                if (context.mounted) {
                  ScaffoldMessenger.of(context).showSnackBar(
                    AppTheme.snackBar(
                      context,
                      l.cloneBudgetError(ApiError.message(e)),
                      severity: AppSeverity.danger,
                    ),
                  );
                }
              }
            },
          ),
        ),
      ),
    );
  }
}
