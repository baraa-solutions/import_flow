import '../../../core/localization/app_localizations.dart';
import '../../../core/localization/system_messages/system_message_renderer.dart';
import '../../../core/services/display_name_resolver.dart';
import '../../import_files/models/import_file_model.dart';

class SmartTaskModel {
  final int taskId;
  final String taskCode;
  final String title;
  final String? description;
  final String taskType; // System Generated, Manual To-Do
  final int? importFileId;
  final String? importFileCode;
  final String? phaseName;
  final String assignedUser;
  final String priority; // Low, Medium, High, Critical
  final String reminderType; // Supplier, Bank, Shipping Line, Broker, Document, ETA, General
  final String? dueDate;
  final String? reminderDate;
  final String status; // Pending, In Progress, Completed, Cancelled
  final String? notes;
  final String? attachmentUrl;
  final bool isAutoClosed;
  final bool isActive;
  final String createdAt;
  final String createdBy;
  /// System message code of title/description/notes (null for user tasks and legacy rows).
  final String? msgCode;
  final Map<String, dynamic>? msgParams;
  /// Lifecycle step the task belongs to (e.g. STEP_06), when generated by the lifecycle board.
  final String? stepCode;

  SmartTaskModel({
    required this.taskId,
    required this.taskCode,
    required this.title,
    this.description,
    required this.taskType,
    this.importFileId,
    this.importFileCode,
    this.phaseName,
    required this.assignedUser,
    required this.priority,
    required this.reminderType,
    this.dueDate,
    this.reminderDate,
    required this.status,
    this.notes,
    this.attachmentUrl,
    required this.isAutoClosed,
    required this.isActive,
    required this.createdAt,
    required this.createdBy,
    this.msgCode,
    this.msgParams,
    this.stepCode,
  });

  /// The title rendered from [msgCode], or null when the task has no usable code (user tasks,
  /// legacy rows): callers then clean the stored [title] (e.g. DisplayNameResolver.cleanTaskTitle).
  String? renderedTitle(AppLocalizations l10n) => SystemMessageRenderer.tryRender(
      code: msgCode, params: msgParams, part: SystemMessagePart.title, l10n: l10n);

  /// The description rendered from [msgCode], or null when it cannot be rendered.
  String? renderedDescription(AppLocalizations l10n) => SystemMessageRenderer.tryRender(
      code: msgCode, params: msgParams, part: SystemMessagePart.body, l10n: l10n);

  /// Title to show: the rendered system message, else the cleaned stored title.
  String displayTitle(AppLocalizations l10n) =>
      renderedTitle(l10n) ?? DisplayNameResolver.cleanTaskTitle(title, isArabic: l10n.isArabic);

  /// Description to show: the rendered system message, else the resolved stored description
  /// ([orNotes] falls back to the stored notes when there is no description).
  String displayDescription(AppLocalizations l10n, {List<ImportFileModel>? shipments, bool orNotes = false}) =>
      renderedDescription(l10n) ??
      DisplayNameResolver.resolveTaskDescription(
        orNotes ? (description ?? notes) : description,
        isArabic: l10n.isArabic,
        shipmentCode: importFileCode,
        shipments: shipments,
      );

  /// [notes] in the user's language; the stored text when there is no usable code.
  String? localizedNotes(AppLocalizations l10n) =>
      SystemMessageRenderer.tryRender(code: msgCode, params: msgParams, part: SystemMessagePart.note, l10n: l10n) ??
      notes;

  factory SmartTaskModel.fromJson(Map<String, dynamic> json) {
    return SmartTaskModel(
      taskId: json['task_id'] ?? 0,
      taskCode: json['task_code'] ?? '',
      title: json['title'] ?? '',
      description: json['description'],
      taskType: json['task_type'] ?? 'Manual To-Do',
      importFileId: json['import_file_id'],
      importFileCode: json['import_file_code'],
      phaseName: json['phase_name'],
      assignedUser: json['assigned_user'] ?? 'Kamal',
      priority: json['priority'] ?? 'Medium',
      reminderType: json['reminder_type'] ?? 'General Reminder',
      dueDate: json['due_date'],
      reminderDate: json['reminder_date'],
      status: json['status'] ?? 'Pending',
      notes: json['notes'],
      attachmentUrl: json['attachment_url'],
      isAutoClosed: json['is_auto_closed'] ?? false,
      isActive: json['is_active'] ?? true,
      createdAt: json['created_at'] ?? '',
      createdBy: json['created_by'] ?? 'System',
      msgCode: SystemMessageRenderer.parseCode(json['msg_code']),
      msgParams: SystemMessageRenderer.parseParams(json['msg_params']),
      stepCode: SystemMessageRenderer.parseCode(json['step_code']),
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'task_id': taskId,
      'task_code': taskCode,
      'title': title,
      'description': description,
      'task_type': taskType,
      'import_file_id': importFileId,
      'import_file_code': importFileCode,
      'phase_name': phaseName,
      'assigned_user': assignedUser,
      'priority': priority,
      'reminder_type': reminderType,
      'due_date': dueDate,
      'reminder_date': reminderDate,
      'status': status,
      'notes': notes,
      'attachment_url': attachmentUrl,
      'is_auto_closed': isAutoClosed,
      'is_active': isActive,
      'created_at': createdAt,
      'created_by': createdBy,
      if (msgCode != null) 'msg_code': msgCode,
      if (msgParams != null) 'msg_params': msgParams,
      if (stepCode != null) 'step_code': stepCode,
    };
  }
}

